-- 3. 핵심역량 및 진단 도메인 (Competency & Assessment)
-- ============================================================================

CREATE TABLE competency (
                            competency_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            parent_competency_id    INTEGER REFERENCES competency(competency_id),
                            competency_code         VARCHAR(20) NOT NULL UNIQUE,
                            competency_name         VARCHAR(100) NOT NULL,
                            english_name            VARCHAR(150),
                            description             TEXT,
                            display_order           INTEGER NOT NULL,
                            is_active               BOOLEAN NOT NULL DEFAULT TRUE,
                            created_by              INTEGER NOT NULL,
                            created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                            updated_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE assessment_round (
                                  assessment_round_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  assessment_name         VARCHAR(200) NOT NULL,
                                  academic_year           INTEGER NOT NULL,
                                  semester_code           VARCHAR(20) NOT NULL,
                                  assessment_type         VARCHAR(20) NOT NULL,
                                  starts_at               TIMESTAMPTZ NOT NULL,
                                  ends_at                 TIMESTAMPTZ NOT NULL,
                                  target_condition        JSONB,
                                  round_status            VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
                                  created_by              INTEGER NOT NULL,
                                  created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                  updated_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                  CONSTRAINT uq_assessment_round_period_type UNIQUE (academic_year, semester_code, assessment_type)
);

CREATE TABLE assessment_question (
                                     question_id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     competency_id           INTEGER NOT NULL REFERENCES competency(competency_id),
                                     previous_question_id    INTEGER REFERENCES assessment_question(question_id),
                                     version_no              INTEGER NOT NULL DEFAULT 1,
                                     question_text           TEXT NOT NULL,
                                     is_reverse              BOOLEAN NOT NULL DEFAULT FALSE,
                                     response_options        JSONB NOT NULL,
                                     is_active               BOOLEAN NOT NULL DEFAULT TRUE,
                                     created_by              INTEGER NOT NULL,
                                     created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                     CONSTRAINT uq_assessment_question_previous_version UNIQUE (previous_question_id, version_no)
);

CREATE TABLE assessment_round_question (
                                           assessment_round_id     INTEGER NOT NULL REFERENCES assessment_round(assessment_round_id),
                                           question_id             INTEGER NOT NULL REFERENCES assessment_question(question_id),
                                           display_order           INTEGER NOT NULL,
                                           created_by              INTEGER NOT NULL,
                                           PRIMARY KEY (assessment_round_id, question_id),
                                           CONSTRAINT uq_assessment_round_question_order UNIQUE (assessment_round_id, display_order)
);

CREATE TABLE assessment_attempt (
                                    attempt_id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    assessment_round_id     INTEGER NOT NULL REFERENCES assessment_round(assessment_round_id),
                                    student_id              INTEGER NOT NULL REFERENCES app_user(user_id),
                                    user_consent_id         INTEGER REFERENCES user_consent(user_consent_id),
                                    attempt_status          VARCHAR(20) NOT NULL DEFAULT 'NOT_STARTED',
                                    started_at              TIMESTAMPTZ,
                                    saved_at                TIMESTAMPTZ,
                                    submitted_at            TIMESTAMPTZ,
                                    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                    CONSTRAINT uq_assessment_attempt_round_student UNIQUE (assessment_round_id, student_id)
);

CREATE TABLE assessment_response (
                                     response_id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     attempt_id              INTEGER NOT NULL REFERENCES assessment_attempt(attempt_id),
                                     question_id             INTEGER NOT NULL REFERENCES assessment_question(question_id),
                                     selected_value          NUMERIC(10, 2) NOT NULL,
                                     saved_at                TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                     created_by              INTEGER NOT NULL,
                                     CONSTRAINT uq_assessment_response_attempt_question UNIQUE (attempt_id, question_id)
);

CREATE TABLE assessment_score (
                                  assessment_score_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  attempt_id              INTEGER NOT NULL REFERENCES assessment_attempt(attempt_id),
                                  competency_id           INTEGER NOT NULL REFERENCES competency(competency_id),
                                  raw_score               NUMERIC(10, 2) NOT NULL,
                                  converted_score         NUMERIC(10, 2) NOT NULL,
                                  percentile              NUMERIC(6, 3),
                                  calculated_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                  CONSTRAINT uq_assessment_score_attempt_competency UNIQUE (attempt_id, competency_id)
);


