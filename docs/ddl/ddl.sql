CREATE TABLE counseling_assignment (
                                       counseling_assignment_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                       counseling_reservation_id INTEGER NOT NULL REFERENCES counseling_reservation(counseling_reservation_id),
