-- 2. 학적 도메인 (Academic)
-- ============================================================================

CREATE TABLE student_academic_detail (
                                         user_id              INTEGER PRIMARY KEY REFERENCES app_user(user_id),
                                         major_code_id        INTEGER NOT NULL,
                                         advisor_user_id      INTEGER REFERENCES app_user(user_id),
                                         photo_file_group_id  INTEGER REFERENCES file_group(file_group_id),
                                         birth_date           DATE NOT NULL,
                                         gender               CHAR(1) NOT NULL CHECK (gender IN ('M', 'F')),
                                         zipcode              VARCHAR(10),
                                         address_basic        VARCHAR(255),
                                         address_detail       VARCHAR(255),
                                         guardian_phone       VARCHAR(30),
                                         grade                SMALLINT NOT NULL CHECK (grade BETWEEN 1 AND 4),
                                         completed_semesters  SMALLINT,
                                         degree_name          VARCHAR(50),
                                         degree_no            VARCHAR(50),
                                         created_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                         updated_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                         major_code_group     VARCHAR(50) GENERATED ALWAYS AS ('MAJOR') STORED,
                                         CONSTRAINT fk_sad_major_code_group FOREIGN KEY (major_code_id, major_code_group) REFERENCES common_code (code_id, code_group)
);

CREATE INDEX idx_sad_major ON student_academic_detail(major_code_id);
CREATE INDEX idx_sad_grade ON student_academic_detail(grade);

CREATE TABLE student_academic_change (
                                         student_academic_change_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         student_id                      INTEGER NOT NULL REFERENCES app_user(user_id),
                                         change_date                     DATE NOT NULL,
                                         change_type_code_id             INTEGER NOT NULL,
                                         change_reason_code_id           INTEGER REFERENCES common_code(code_id),
                                         military_status                 VARCHAR(20),
                                         scheduled_return_year           SMALLINT,
                                         scheduled_return_semester_code  VARCHAR(20),
                                         note                            VARCHAR(500),
                                         created_by                      INTEGER NOT NULL,
                                         created_at                      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                         change_type_code_group          VARCHAR(50) GENERATED ALWAYS AS ('ACADEMIC_CHANGE_TYPE') STORED,
                                         change_reason_code_group        VARCHAR(50) GENERATED ALWAYS AS ('ACADEMIC_CHANGE_REASON') STORED,
                                         CONSTRAINT fk_sac_change_type_code_group FOREIGN KEY (change_type_code_id, change_type_code_group) REFERENCES common_code (code_id, code_group),
                                         CONSTRAINT fk_sac_change_reason_code_group FOREIGN KEY (change_reason_code_id, change_reason_code_group) REFERENCES common_code (code_id, code_group)
);

CREATE INDEX idx_sac_student_date ON student_academic_change(student_id, change_date DESC, student_academic_change_id DESC);


