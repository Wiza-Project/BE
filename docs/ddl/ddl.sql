CREATE TABLE app_user (
                          user_id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          login_id            VARCHAR(100) NOT NULL UNIQUE,
                          password_hash       VARCHAR(255) NOT NULL,
                          user_name           VARCHAR(100) NOT NULL,
                          user_type           VARCHAR(30) NOT NULL,
                          department_code     VARCHAR(50),
                          academic_status     VARCHAR(30),
                          email               VARCHAR(255),
                          phone_number        VARCHAR(30),
                          is_active           BOOLEAN NOT NULL DEFAULT TRUE,
                          created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                          updated_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE consent_policy (
                                consent_policy_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                consent_type        VARCHAR(40) NOT NULL,
                                module_code         VARCHAR(30) NOT NULL,
                                version             VARCHAR(30) NOT NULL,
                                title               VARCHAR(200) NOT NULL,
                                content             TEXT NOT NULL,
                                is_required         BOOLEAN NOT NULL,
                                effective_from      TIMESTAMPTZ NOT NULL,
                                effective_to        TIMESTAMPTZ,
                                is_active           BOOLEAN NOT NULL DEFAULT TRUE,
                                created_by          INTEGER NOT NULL,
                                created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                CONSTRAINT uq_consent_policy_type_module_version UNIQUE (consent_type, module_code, version)
);

CREATE TABLE user_consent (
                              user_consent_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              user_id             INTEGER NOT NULL REFERENCES app_user(user_id),
                              consent_policy_id   INTEGER NOT NULL REFERENCES consent_policy(consent_policy_id),
                              consented_at        TIMESTAMPTZ NOT NULL,
                              withdrawn_at        TIMESTAMPTZ,
                              created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uq_user_consent_active
    ON user_consent (user_id, consent_policy_id)
    WHERE withdrawn_at IS NULL;

CREATE TABLE common_code (
                             code_id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             parent_code_id      INTEGER REFERENCES common_code(code_id),
                             code_group          VARCHAR(50) NOT NULL,
                             code                VARCHAR(50) NOT NULL,
                             code_name           VARCHAR(100) NOT NULL,
                             description         TEXT,
                             sort_order          INTEGER NOT NULL DEFAULT 0,
                             is_active           BOOLEAN NOT NULL DEFAULT TRUE,
                             created_by          INTEGER NOT NULL,
                             created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                             updated_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                             CONSTRAINT uq_common_code_group_code UNIQUE (code_group, code),
                             CONSTRAINT uq_common_code_id_group UNIQUE (code_id, code_group)
);

CREATE TABLE file_group (
                            file_group_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE stored_file (
                             stored_file_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             file_group_id       INTEGER NOT NULL REFERENCES file_group(file_group_id),
                             original_file_name  VARCHAR(255) NOT NULL,
                             storage_key         VARCHAR(1000) NOT NULL UNIQUE,
                             content_type        VARCHAR(100),
                             file_size           BIGINT NOT NULL,
                             uploaded_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                             created_by          INTEGER NOT NULL
);

CREATE TABLE audit_log (
                           audit_log_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           actor_user_id       INTEGER,
                           resource_type       VARCHAR(80) NOT NULL,
                           resource_id         INTEGER,
                           action_code         VARCHAR(30) NOT NULL,
                           action_result       VARCHAR(20) NOT NULL,
                           access_reason       VARCHAR(500),
                           ip_address          VARCHAR(45),
                           user_agent          VARCHAR(500),
                           created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE notification (
                              notification_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              recipient_user_id   INTEGER NOT NULL REFERENCES app_user(user_id),
                              notification_type   VARCHAR(40) NOT NULL,
                              module_code         VARCHAR(30) NOT NULL,
                              channel             VARCHAR(20) NOT NULL,
                              title               VARCHAR(200) NOT NULL,
                              content             TEXT NOT NULL,
                              delivery_status     VARCHAR(20) NOT NULL DEFAULT 'PENDING',
                              retry_count         INTEGER NOT NULL DEFAULT 0,
                              failure_reason      TEXT,
                              sent_at             TIMESTAMPTZ,
                              read_at             TIMESTAMPTZ,
                              created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE board_post (
                            board_post_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            parent_post_id      INTEGER REFERENCES board_post(board_post_id),
                            file_group_id       INTEGER REFERENCES file_group(file_group_id),
                            author_user_id      INTEGER NOT NULL REFERENCES app_user(user_id),
                            board_type          VARCHAR(20) NOT NULL,
                            module_code         VARCHAR(30) NOT NULL,
                            category_code       VARCHAR(40),
                            title               VARCHAR(300) NOT NULL,
                            content             TEXT NOT NULL,
                            is_private          BOOLEAN NOT NULL DEFAULT FALSE,
                            is_pinned           BOOLEAN NOT NULL DEFAULT FALSE,
                            post_status         VARCHAR(20) NOT NULL DEFAULT 'PUBLISHED',
                            deleted_at          TIMESTAMPTZ,
                            created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                            updated_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);


