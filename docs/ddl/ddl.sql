CREATE TABLE counseling_session (
                                    counseling_session_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    counseling_assignment_id  INTEGER NOT NULL REFERENCES counseling_assignment(counseling_assignment_id),
